#!/usr/bin/env python3
"""Generate the TechDocs page docs/inventory.md from inventory.yaml.

Backstage RAG-AI ("Ask AI") answers from chunks of about 1000 characters and
only sees a handful of them per question. A list of VMs spread over one catalog
entity per VM cannot be counted from that; this page puts the count and the
names into its first paragraph, so a single chunk answers "how many VMs".

Output:
  ../docs/inventory.md   - committed; `make check` fails when it is stale

Usage: python3 gen_docs.py [--in inventory.yaml] [--out ../docs/inventory.md]
"""

from __future__ import annotations

import argparse
import ipaddress
import sys
from collections import defaultdict
from pathlib import Path

import yaml


def ip_key(h: dict) -> tuple:
    try:
        return (0, int(ipaddress.ip_address(str(h.get("ip")))))
    except ValueError:
        return (1, str(h.get("ip")))


def cell(value) -> str:
    """Table cell: no line breaks, no pipes."""
    return " ".join(str(value or "").split()).replace("|", "\\|") or "-"


def vm_section(hosts: list[dict]) -> list[str]:
    by_hv: dict[str, list[dict]] = defaultdict(list)
    for h in hosts:
        if h.get("vm"):
            by_hv[h["vm"]].append(h)

    out: list[str] = []
    for hv, vms in sorted(by_hv.items()):
        vms.sort(key=lambda h: str(h["hostname"]))
        hv_host = next(
            (h for h in hosts if h.get("system") == hv and h.get("kind") == "hypervisor"),
            {},
        )
        names = ", ".join(f"`{h['hostname']}`" for h in vms)
        out += [
            f"## Virtual machines on {hv.capitalize()}",
            "",
            f"There are **{len(vms)} virtual machines** on {hv.capitalize()}"
            + (f" (host `{hv_host['hostname']}`, {hv_host['ip']})" if hv_host else "")
            + f": {names}. Each one is a cluster node or a single host;"
            " Scaffolder templates, catalog locations and VM templates such as"
            " `harvester-vm` or `harvester-vm-template` are **not** VMs."
            " Backstage lists each VM as a Resource `<name>-harvester-vm`;"
            " Rancher-provisioned cluster nodes carry a pool name in Harvester"
            " (e.g. `app-dev-hv-pool1-…`).",
            "",
            "| VM | IP | Kind | Cluster |",
            "|---|---|---|---|",
        ]
        out += [
            f"| `{h['hostname']}` | {h['ip']} | {cell(h.get('kind'))} | {cell(h.get('cluster'))} |"
            for h in vms
        ]
        out.append("")
    return out


def host_table(hosts: list[dict]) -> list[str]:
    out = [
        "## All hosts",
        "",
        f"{len(hosts)} addresses in the inventory, sorted by IP.",
        "",
        "| Hostname | IP | Kind | System | Cluster | Harvester VM |",
        "|---|---|---|---|---|---|",
    ]
    for h in sorted(hosts, key=ip_key):
        out.append(
            f"| `{h['hostname']}` | {h['ip']} | {cell(h.get('kind'))} | {cell(h.get('system'))}"
            f" | {cell(h.get('cluster'))} | {'yes' if h.get('vm') else '-'} |"
        )
    out.append("")
    return out


def systems(hosts: list[dict]) -> list[str]:
    grouped: dict[str, list[dict]] = defaultdict(list)
    for h in hosts:
        grouped[h.get("system", "no system")].append(h)

    out = ["## Systems", ""]
    for system, entries in sorted(grouped.items()):
        out += [f"### {system}", ""]
        for h in sorted(entries, key=ip_key):
            where = f" (VM on {h['vm'].capitalize()})" if h.get("vm") else ""
            out.append(f"- **`{h['hostname']}`** {h['ip']}{where}: {cell(h.get('description'))}")
            for svc in h.get("services", []) or []:
                addr = svc.get("fqdn") or svc.get("ip") or h["ip"]
                if svc.get("port"):
                    addr = f"{addr}:{svc['port']}"
                out.append(f"    - {svc['name']} (`{addr}`): {cell(svc.get('description'))}")
        out.append("")
    return out


def render(data: dict) -> str:
    hosts = data.get("hosts", []) or []
    site = data.get("site", {}) or {}
    lines = [
        "# System inventory",
        "",
        "<!-- Generated by system-inventory/gen_docs.py from"
        " system-inventory/inventory.yaml. Do not edit; run `make docs`. -->",
        "",
        f"{site.get('name', 'Lab')}: {site.get('subtitle', 'hosts and services')}."
        " Source: `system-inventory/inventory.yaml`; the interactive version with"
        " the topology diagram is on GitHub Pages under `/inventory/`.",
        "",
    ]
    lines += vm_section(hosts)
    lines += host_table(hosts)
    lines += systems(hosts)
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--in", dest="src", default="inventory.yaml")
    ap.add_argument("--out", dest="out", default="../docs/inventory.md")
    args = ap.parse_args()

    data = yaml.safe_load(Path(args.src).read_text()) or {}
    Path(args.out).write_text(render(data))
    print(f"wrote: {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
